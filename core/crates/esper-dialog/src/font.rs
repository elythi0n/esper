//! The glyphs a consent question is drawn with.
//!
//! # Why this font is in the repository
//!
//! The alternative is the X server's own core fonts, which are one call away
//! and were the first thing tried. They are also a resource somebody else's
//! machine may not have, in a subsystem X11 deprecated two decades ago — and
//! the failure mode is a security prompt that cannot be drawn. A prompt is the
//! one thing in this product that must look the same on every machine and
//! must not fail for want of something installed.
//!
//! It also removes a class of hazard rather than defending against it. A
//! bitmap renderer has no escape sequences, no shaping, no ligatures and no
//! substitution: a device name is a sequence of glyph lookups, and a character
//! there is either one of the ninety-five below or a box that says it is not.
//! The name is peer-supplied, and the identity somebody compares is the
//! fingerprint underneath it, which is this project's own word list and is
//! always drawable.
//!
//! # The shape of it
//!
//! Five wide, nine tall, baseline on row six, so rows seven and eight are
//! descender space for `g j p q y` and for a comma. Authored as art rather
//! than as hex because a font somebody cannot read is a font nobody can check
//! — see `every_printable_character_has_a_glyph` and the test that prints a
//! pangram for a person to look at.

/// One glyph's width in pixels, before scaling.
pub const GLYPH_WIDTH: usize = 5;

/// One glyph's height in pixels, before scaling.
pub const GLYPH_HEIGHT: usize = 9;

/// The gap between glyphs, before scaling, so text is not a hedge.
pub const TRACKING: usize = 1;

/// How far one character advances, before scaling.
pub const ADVANCE: usize = GLYPH_WIDTH + TRACKING;

/// The first and last characters this font covers.
pub const FIRST: char = ' ';
/// The last character this font covers.
pub const LAST: char = '~';

/// A glyph, as one bit per pixel with the low five bits of each row used.
///
/// Row zero is the top. Bit four is the leftmost pixel, so a row reads the way
/// it is written.
pub type Glyph = [u8; GLYPH_HEIGHT];

/// What is drawn for a character this font does not have.
///
/// A hollow box rather than a space or a guess: a name with a character we
/// cannot draw should look like a name with a character we cannot draw, and a
/// silent gap would let two different names look identical.
pub const UNKNOWN: Glyph = [
    0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111, 0b00000, 0b00000,
];

/// The glyph for `c`, or [`UNKNOWN`] where there is none.
#[must_use]
pub fn glyph(c: char) -> Glyph {
    if c < FIRST || c > LAST {
        return UNKNOWN;
    }
    let at = (c as usize) - (FIRST as usize);
    GLYPHS.get(at).copied().unwrap_or(UNKNOWN)
}

/// Whether this font can draw `c` as itself.
#[must_use]
pub fn drawable(c: char) -> bool {
    (FIRST..=LAST).contains(&c)
}

/// How wide `text` is at `scale`, in pixels, with no trailing tracking.
#[must_use]
pub fn width_of(text: &str, scale: usize) -> usize {
    let n = text.chars().count();
    if n == 0 {
        return 0;
    }
    (n * ADVANCE - TRACKING) * scale
}

